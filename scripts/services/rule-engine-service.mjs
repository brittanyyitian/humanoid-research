import path from "node:path";
import { DATA_DIR } from "../data-utils.mjs";
import { dateFrom, hash } from "./router-service.mjs";

const CONTRACT_VERSION = "skill_rule_contract_v0";

export function ruleOutputPath(ruleOutputId) {
  return path.join(DATA_DIR, "rule_outputs", `${ruleOutputId}.json`);
}

export function applySkillRule({ task, artifact, source, fetchRun, routeDecision, rawPayload, processedAt }) {
  const ruleContext = { task, artifact, source, fetchRun, routeDecision, rawPayload, processedAt };
  const base =
    task.pipeline === "product_pipeline"
      ? productRule(ruleContext)
      : task.pipeline === "filing_pipeline"
        ? filingRule(ruleContext)
        : genericRule(ruleContext);

  const claim = base.claimCandidates[0];
  const date = dateFrom(claim.occurredAt || claim.publishedAt || artifact.publishedAt || artifact.firstSeenAt);
  const id = `rout_${date.replaceAll("-", "_")}_${slug(base.ruleId)}_${hash(
    `${task.id}|${artifact.id}|${base.ruleId}|${claim.text}`,
    10
  )}`;

  return {
    id,
    contractVersion: CONTRACT_VERSION,
    ruleId: base.ruleId,
    pipeline: task.pipeline,
    rawArtifactId: artifact.id,
    sourceId: artifact.sourceId,
    routeDecisionId: routeDecision.id,
    generatedAt: processedAt,
    payloadStatus: rawPayload?.retrievalStatus || "missing",
    claimCandidates: base.claimCandidates,
    evidenceCandidates: base.evidenceCandidates,
    unknowns: base.unknowns || [],
    followupHints: base.followupHints || [],
    dataGaps: normalizeDataGaps([...(fetchRun.gaps || []), ...(base.dataGaps || [])]),
    extractedFields: normalizeExtractedFields(base.extractedFields || []),
    timeFields: {
      occurredAt: claim.occurredAt || null,
      publishedAt: claim.publishedAt ?? artifact.publishedAt ?? null,
      firstSeenAt: artifact.firstSeenAt,
      capturedAt: artifact.capturedAt,
      processedAt,
      dueAt: claim.dueAt || null,
      resolvedAt: null,
    },
    reviewRequirements: base.reviewRequirements || defaultReviewRequirements(),
    notes: base.notes || "Skill Rule Contract v0 output. Review is required before promotion.",
  };
}

export function claimDraftFromRuleOutput(ruleOutput) {
  const claim = ruleOutput.claimCandidates[0];
  const evidence = ruleOutput.evidenceCandidates[0];
  return {
    ...claim,
    relation: evidence.relation,
    sourceLevel: evidence.sourceLevel,
    strength: evidence.strength,
    quote: evidence.quote,
    evidenceNotes: evidence.notes,
    ruleOutputId: ruleOutput.id,
    unknowns: ruleOutput.unknowns,
    followupHints: ruleOutput.followupHints,
    dataGaps: ruleOutput.dataGaps,
    reviewRequirements: ruleOutput.reviewRequirements,
  };
}

function productRule({ artifact, source, routeDecision, rawPayload, processedAt }) {
  const product = productDetails(rawPayload);
  const productName = clean(product?.name || product?.productName || product?.model);
  const specs = normalizeSpecList(product?.specs || product?.parameters);
  const deliveryWindow = clean(product?.deliveryWindow || product?.delivery_window || product?.delivery);
  const partners = normalizeStringList(product?.partners || product?.customers || product?.partnerOrCustomer);
  const releaseDate = clean(product?.releaseDate || product?.occurredAt);
  const conflicts = normalizeConflicts(product?.conflicts || product?.counterEvidence || rawPayload?.content?.conflicts);

  if (productName || specs.length || deliveryWindow || partners.length || conflicts.length) {
    return richProductRule({
      artifact,
      source,
      routeDecision,
      rawPayload,
      processedAt,
      productName,
      specs,
      deliveryWindow,
      partners,
      releaseDate,
      conflicts,
      sourceQuote: clean(product?.sourceQuote || product?.quote),
    });
  }

  const claim = {
    claimType: "product_release",
    text: `${artifact.publisher}存在官方产品材料《${artifact.title}》。`,
    normalizedFact: `${artifact.publisher} has official product material for "${artifact.title}".`,
    confidence: routeDecision.confidence === "high" ? "medium" : "low",
    publishedAt: artifact.publishedAt || null,
    whyNow: "Router 将原始材料分配至 product_pipeline，Skill Rule Contract 生成待审核产品事实候选。",
    notes: `Generated by product_pipeline rule at ${processedAt}. This candidate is not promoted truth.`,
  };
  const unknowns = [
    unknown("product_name", "需要人工确认标题是否等同于标准产品名。", "medium"),
    unknown("product_specs", "未从材料中结构化抽取关键参数。", "medium"),
    unknown("delivery_window", "未确认交付时间、量产时间或验证窗口。", "medium"),
    unknown("partner_or_customer", "未确认是否涉及合作方、客户或供应链对象。", "low"),
  ];
  const followupHints = [
    {
      kind: "product_spec_review",
      description: "复核原始材料，提取产品名、参数、发布时间、交付窗口和合作方。",
      priority: "high",
      dueAt: null,
    },
  ];
  return {
    ruleId: "product_material_v0",
    claimCandidates: [claim],
    evidenceCandidates: [
      {
        relation: "supports",
        sourceLevel: source.evidenceLevel || "A",
        strength: source.evidenceLevel === "A" ? "medium" : "weak",
        quote: artifact.title,
        notes: "Official product material supports the existence of a product-related candidate.",
      },
    ],
    unknowns,
    followupHints,
    dataGaps: rawPayload?.retrievalStatus === "captured_payload" ? [] : [rawPayloadGap()],
    reviewRequirements: [
      reviewRequirement("confirm_product_identity", "确认标题、页面正文和标准产品名是否一致。", true),
      reviewRequirement("extract_product_fields", "补全产品名、参数、交付窗口、合作方和待验证点。", true),
    ],
    notes: "Product rule v0 preserves the existing claim text but exposes missing richness as unknowns and follow-up hints.",
  };
}

function richProductRule({
  artifact,
  source,
  routeDecision,
  rawPayload,
  processedAt,
  productName,
  specs,
  deliveryWindow,
  partners,
  releaseDate,
  conflicts,
  sourceQuote,
}) {
  const subject = productName || artifact.title;
  const detailParts = [];
  if (specs.length) detailParts.push(`参数线索：${specs.join("；")}`);
  if (deliveryWindow) detailParts.push(`交付/验证窗口：${deliveryWindow}`);
  if (partners.length) detailParts.push(`合作方/客户线索：${partners.join("、")}`);
  const detailText = detailParts.length ? `，${detailParts.join("，")}` : "";
  const occurredAt = releaseDate ? dateFrom(releaseDate) : null;
  const claim = {
    claimType: "product_release",
    text: `${artifact.publisher}披露${subject}产品材料${detailText}。`,
    normalizedFact: `${artifact.publisher} product material for "${subject}" includes specs=${specs.join(
      "; "
    )}, deliveryWindow=${deliveryWindow || "unknown"}, partners=${partners.join("; ") || "unknown"}.`,
    confidence: routeDecision.confidence === "high" && conflicts.length === 0 ? "medium" : "low",
    occurredAt,
    publishedAt: artifact.publishedAt || null,
    whyNow: "Router 将原始材料分配至 product_pipeline，Skill Rule Contract 从结构化产品 payload 生成待审核事实候选。",
    notes: `Generated by product_pipeline rich product rule at ${processedAt}. This candidate is not promoted truth.`,
  };

  const unknowns = [];
  if (!productName) unknowns.push(unknown("product_name", "结构化 payload 未提供标准产品名。", "medium"));
  if (specs.length === 0) unknowns.push(unknown("product_specs", "结构化 payload 未提供关键参数。", "medium"));
  if (!deliveryWindow) unknowns.push(unknown("delivery_window", "结构化 payload 未提供交付或验证窗口。", "medium"));
  if (partners.length === 0) unknowns.push(unknown("partner_or_customer", "结构化 payload 未提供合作方或客户线索。", "low"));
  if (conflicts.length > 0) {
    unknowns.push(unknown("source_conflict", "至少一个外部线索与产品材料中的时间、参数或合作方描述不一致。", "high"));
  }

  const evidenceCandidates = [
    {
      relation: "supports",
      sourceLevel: source.evidenceLevel || "A",
      strength: source.evidenceLevel === "A" && conflicts.length === 0 ? "strong" : "medium",
      quote: sourceQuote || artifact.title,
      notes: "Structured product payload supports a richer product-release candidate. Review is still required.",
    },
    ...conflicts.map((conflict) => ({
      relation: conflict.relation || "refutes",
      sourceLevel: conflict.sourceLevel || "C",
      strength: conflict.strength || "weak",
      quote: conflict.quote,
      notes: conflict.reason || "External signal conflicts with the product payload and must be resolved before promotion.",
    })),
  ];

  const followupHints = [
    {
      kind: "verify_product_fields",
      description: "复核原始材料中的产品名、参数、交付/验证窗口和合作方线索。",
      priority: "high",
      dueAt: null,
    },
  ];
  if (deliveryWindow) {
    followupHints.push({
      kind: "delivery_window_verification",
      description: "跟踪交付/验证窗口是否有后续公告、客户案例或正式披露确认。",
      priority: "high",
      dueAt: null,
    });
  }
  if (conflicts.length > 0) {
    followupHints.push({
      kind: "resolve_conflicting_sources",
      description: "对比官方材料、公告和媒体线索，解决参数、时间或合作方冲突。",
      priority: "high",
      dueAt: null,
    });
  }

  const dataGaps = rawPayload?.retrievalStatus === "captured_payload" ? [] : [rawPayloadGap()];
  for (const conflict of conflicts) {
    dataGaps.push({
      kind: "conflicting_product_signal",
      description: conflict.reason || "Product payload has a conflicting external signal.",
      severity: "high",
    });
  }

  return {
    ruleId: "product_material_v0",
    claimCandidates: [claim],
    evidenceCandidates,
    unknowns,
    followupHints,
    dataGaps,
    extractedFields: [
      extractedField("product_name", productName),
      ...specs.map((spec) => extractedField("product_spec", spec)),
      extractedField("delivery_window", deliveryWindow),
      ...partners.map((partner) => extractedField("partner_or_customer", partner)),
    ].filter(Boolean),
    reviewRequirements: [
      reviewRequirement("verify_product_source", "打开原始材料确认产品名、页面正文和发布时间。", true),
      reviewRequirement("verify_product_specs", "核对参数是否来自官方正文、图片、表格或发布会材料。", true),
      reviewRequirement("verify_delivery_window", "交付/验证窗口必须找到后续公告或可信来源确认。", Boolean(deliveryWindow)),
      reviewRequirement("resolve_conflicting_sources", "存在冲突线索时，promotion 前必须先解决冲突。", conflicts.length > 0),
    ],
    notes: "Product rule v0 can express structured product fields while keeping all outputs in review-gated candidate state.",
  };
}

function filingRule({ artifact, source, rawPayload, processedAt }) {
  const serenity = rawPayload?.content?.serenityBridge;
  if (serenity?.dataset === "filings_announcements") {
    const item = serenity.payload || {};
    const publishedAt = item.announcement_date || artifact.publishedAt;
    return {
      ruleId: "serenity_filing_announcement_v0",
      claimCandidates: [
        {
          claimType: "filing",
          text: `${entityDisplayName(rawPayload, artifact)}披露公告《${artifact.title}》（${dateFrom(publishedAt)}）。`,
          normalizedFact: `${entityDisplayName(rawPayload, artifact)} disclosed filing "${artifact.title}" on ${dateFrom(
            publishedAt
          )}.`,
          confidence: "medium",
          occurredAt: dateFrom(publishedAt),
          publishedAt,
          whyNow: "Serenity Bridge 接入上市公司公告数据，Skill Rule Contract 生成待人工审核的披露事实候选。",
          notes: `Generated from Serenity filings_announcements at ${processedAt}. Candidate only; no automatic promotion.`,
        },
      ],
      evidenceCandidates: [
        {
          relation: "supports",
          sourceLevel: source.evidenceLevel || "A",
          strength: source.evidenceLevel === "A" ? "strong" : "medium",
          quote: artifact.title,
          notes: "Serenity Bridge preserved the announcement payload and source level; reviewer must verify before promotion.",
        },
      ],
      unknowns: [unknown("announcement_materiality", "公告是否与人形机器人产业链相关仍需人工判断。", "medium")],
      followupHints: [
        {
          kind: "filing_materiality_review",
          description: "阅读公告正文，判断是否需要 promotion 为事件、follow-up 或仅归档为背景材料。",
          priority: "medium",
          dueAt: null,
        },
      ],
      dataGaps: [],
      reviewRequirements: [
        reviewRequirement("verify_pdf_source", "打开公告 PDF 或交易所页面确认标题和披露日。", true),
        reviewRequirement("classify_materiality", "判断公告是否构成正式研究事件或仅保留候选。", true),
      ],
      notes: "Filing announcement rule v0 keeps official disclosure evidence strong but blocks automatic promotion.",
    };
  }

  if (serenity?.dataset === "financials") {
    const latest = serenity.payload?.latestPeriod || {};
    const currency = serenity.payload?.currency || "CNY";
    const period = latest.period || artifact.publishedAt;
    const reportType = latest.report_type || "财报";
    const revenue = formatMoney(latest.revenue, currency);
    const netIncome = formatMoney(latest.net_income, currency);
    const operatingCashFlow = formatMoney(latest.operating_cash_flow, currency);
    return {
      ruleId: "serenity_financials_v0",
      claimCandidates: [
        {
          claimType: "financial",
          text: `${entityDisplayName(rawPayload, artifact)}${dateFrom(period)}${reportType}结构化财务数据进入待审核：营收 ${revenue}，净利润 ${netIncome}，经营现金流 ${operatingCashFlow}。`,
          normalizedFact: `${entityDisplayName(rawPayload, artifact)} latest structured financial period ${dateFrom(
            period
          )}: revenue=${latest.revenue}, net_income=${latest.net_income}, operating_cash_flow=${latest.operating_cash_flow}.`,
          confidence: source.evidenceLevel === "A" || source.evidenceLevel === "B" ? "medium" : "low",
          occurredAt: dateFrom(period),
          publishedAt: period,
          whyNow: "Serenity Bridge 接入结构化财报数据，但该来源级别仍需 L0/L1 披露复核。",
          notes: `Generated from Serenity financials at ${processedAt}. Source level=${source.evidenceLevel}; do not treat as verified filing until review.`,
        },
      ],
      evidenceCandidates: [
        {
          relation: "mentions",
          sourceLevel: source.evidenceLevel || "C",
          strength: source.evidenceLevel === "A" ? "strong" : source.evidenceLevel === "B" ? "medium" : "weak",
          quote: `${period} ${reportType}: revenue ${latest.revenue}, net_income ${latest.net_income}`,
          notes: "Structured financial data supports a candidate only; source-level gap remains visible in fetch_runs/dashboard.",
        },
      ],
      unknowns: [
        unknown("official_financial_reconciliation", "结构化财务数据尚未与 L0/L1 正式披露逐项核对。", "high"),
      ],
      followupHints: [
        {
          kind: "financial_reconciliation",
          description: "用公告 PDF、XBRL 或 L1 数据源复核营收、净利、现金流、资产和负债。",
          priority: "high",
          dueAt: null,
        },
      ],
      dataGaps: [],
      reviewRequirements: [
        reviewRequirement("reconcile_l0_l1", "在 promotion 前必须用 L0/L1 披露核对核心财务字段。", true),
        reviewRequirement("avoid_rating_use", "不得将该候选用于评级、买点、仓位或估值结论。", true),
      ],
      notes: "Financial rule v0 preserves Serenity source-level limits and forces review before formal use.",
    };
  }

  return genericFilingRule({ artifact, source, rawPayload, processedAt });
}

