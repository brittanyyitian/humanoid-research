function defaultReviewRequirements() {
  return [reviewRequirement("manual_review", "候选事实必须人工审核后才能 promotion。", true)];
}

function reviewRequirement(kind, description, required) {
  return { kind, description, required };
}

function unknown(field, reason, severity) {
  return { field, reason, severity };
}

function rawPayloadGap() {
  return {
    kind: "raw_payload_not_fetched",
    description: "Rule output was generated from metadata-only payload; full source body still needs capture.",
    severity: "medium",
  };
}

function normalizeDataGaps(rows) {
  const normalized = rows.map((row) => ({
    ...row,
    kind: row.kind || "data_gap",
    description: row.description || row.next_action || row.gap_type || "Unspecified data gap.",
    severity: row.severity || "medium",
  }));
  const seen = new Set();
  return normalized.filter((row) => {
    const key =
      row.kind === "raw_payload_not_fetched"
        ? row.kind
        : `${row.kind}|${row.dataset || ""}|${row.gap_type || ""}|${row.description}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function normalizeExtractedFields(rows) {
  return rows
    .filter((row) => row && row.value !== undefined && row.value !== null && String(row.value).trim() !== "")
    .map((row) => ({
      field: row.field,
      value: String(row.value),
      confidence: row.confidence || "medium",
      source: row.source || "rule_payload",
    }));
}

function productDetails(rawPayload) {
  const content = rawPayload?.content || {};
  return content.product || content.productRelease || content.productSignal || null;
}

function normalizeSpecList(value) {
  if (!value) return [];
  if (Array.isArray(value)) {
    return value
      .map((item) => {
        if (typeof item === "string") return clean(item);
        if (!item || typeof item !== "object") return "";
        const name = clean(item.name || item.label || item.field);
        const specValue = clean(item.value || item.text);
        if (name && specValue) return `${name}: ${specValue}`;
        return name || specValue;
      })
      .filter(Boolean);
  }
  if (typeof value === "object") {
    return Object.entries(value)
      .map(([key, item]) => `${key}: ${item}`)
      .filter(Boolean);
  }
  return [clean(value)].filter(Boolean);
}

function normalizeStringList(value) {
  if (!value) return [];
  if (Array.isArray(value)) return value.map(clean).filter(Boolean);
  return [clean(value)].filter(Boolean);
}

function normalizeConflicts(value) {
  if (!value) return [];
  const rows = Array.isArray(value) ? value : [value];
  return rows
    .map((row) => {
      if (typeof row === "string") {
        return { quote: row, relation: "refutes", sourceLevel: "C", strength: "weak", reason: "Unstructured conflict signal." };
      }
      if (!row || typeof row !== "object") return null;
      const quote = clean(row.quote || row.text || row.description);
      if (!quote) return null;
      return {
        quote,
        relation: row.relation === "updates" ? "updates" : row.relation === "mentions" ? "mentions" : "refutes",
        sourceLevel: ["A", "B", "C", "D"].includes(row.sourceLevel) ? row.sourceLevel : "C",
        strength: ["strong", "medium", "weak"].includes(row.strength) ? row.strength : "weak",
        reason: clean(row.reason || row.notes || row.description),
      };
    })
    .filter(Boolean);
}

function extractedField(field, value) {
  if (!value) return null;
  return { field, value, confidence: "medium", source: "structured_payload" };
}

function entityDisplayName(rawPayload, artifact) {
  const serenity = rawPayload?.content?.serenityBridge;
  return (
    serenity?.entityName ||
    serenity?.payload?.name ||
    serenity?.payload?.security_name ||
    serenity?.payload?.latestPeriod?.security_name ||
    artifact.publisher
  );
}

function formatMoney(value, currency) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "--";
  const unit = currency === "CNY" ? "元" : currency || "";
  const abs = Math.abs(number);
  if (abs >= 100000000) return `${(number / 100000000).toFixed(2)}亿${unit}`;
  if (abs >= 10000) return `${(number / 10000).toFixed(2)}万${unit}`;
  return `${number.toFixed(2)}${unit}`;
}

function clean(value) {
  if (value === undefined || value === null) return "";
  return String(value).trim();
}

function slug(value) {
  const normalized = String(value || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 48);
  return normalized || "rule";
}
